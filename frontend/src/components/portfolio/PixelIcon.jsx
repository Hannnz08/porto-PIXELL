const COLORS = {
  L: "#E2F900",
  C: "#00E5F0",
  O: "#FF5700",
  W: "#FFFFFF",
};

export const PixelIcon = ({ name, size = 24, color, className, style }) => {
  const rows = GRIDS[name] || GRIDS.network;
  const rects = [];
  rows.forEach((row, y) => {
    [...row].forEach((ch, x) => {
      if (ch === "0") return;
      const fill = ch === "1" || ch === "#" ? color || "#000000" : COLORS[ch] || "#000000";
      rects.push(<rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill={fill} />);
    });
  });
  return (
    <svg
      viewBox="0 0 16 16"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      className={className}
      style={style}
      aria-hidden="true"
      focusable="false"
    >
      {rects}
    </svg>
  );
};
